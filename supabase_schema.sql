-- ----------------------------------------------------------------------------
-- 2. Table: employee_audit_logs (Activity & Security Trail)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.employee_audit_logs (
    id TEXT PRIMARY KEY,
    timestamp TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    employee_id TEXT,
    employee_name TEXT,
    employee_username TEXT,
    employee_role TEXT,
    action_type TEXT DEFAULT 'ACTIVITY',
    action_label TEXT DEFAULT 'Action',
    details TEXT DEFAULT '',
    session_id TEXT DEFAULT 'SESS-WEB'
);

-- ----------------------------------------------------------------------------
-- 3. Table: deal_sheets (Interactive Google Sheets & Deal Master)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.deal_sheets (
    id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    cells JSONB DEFAULT '{}'::jsonb,
    rows INTEGER DEFAULT 25,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW())
);

-- ----------------------------------------------------------------------------
-- 4. Table: inquiries (Website Contact & Quote Requests)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.inquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT DEFAULT 'Not provided',
    inquiry_type TEXT DEFAULT 'Direct Message',
    message TEXT DEFAULT '',
    status TEXT DEFAULT 'New'
);

-- ----------------------------------------------------------------------------
-- 5. Table: trades (Marketplace Buy/Sell Orders)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.trades (
    id TEXT PRIMARY KEY DEFAULT ('ORD-' || FLOOR(RANDOM() * 9000 + 1000)::TEXT),
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    order_type TEXT DEFAULT 'BUY',
    project_name TEXT NOT NULL,
    volume NUMERIC DEFAULT 100,
    limit_price NUMERIC DEFAULT 15.00,
    clearing_value NUMERIC DEFAULT 1500.00,
    status TEXT DEFAULT 'Cleared'
);

-- ============================================================================
-- Row Level Security (RLS) & Access Policies
-- Allows the website frontend (anon & authenticated) full access to read/write
